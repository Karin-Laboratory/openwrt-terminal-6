#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Compile the opt-in Air6 Ethernet DTB with the *same prepared kernel tree*.
# This is a non-installable compile gate, not a boot/probe test.
set -euo pipefail
if [[ $# -ne 2 ]]; then
  echo "usage: $0 PREPARED_KERNEL_TREE OUTPUT_DIRECTORY" >&2
  exit 2
fi
kernel="$(realpath "$1")"
out="$(realpath -m "$2")"
source_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
dts="$source_root/board/mt6990-air-terminal-6-ethernet-test.dts"
[[ -f "$kernel/Makefile" && -f "$kernel/include/generated/autoconf.h" ]] || {
  echo "FAIL: expected a configured, prepared kernel tree" >&2; exit 1;
}
[[ -f "$kernel/arch/arm64/boot/dts/mediatek/mt6990.dtsi" ]] || {
  echo "FAIL: kernel lacks matching MT6990 SoC DTSI" >&2; exit 1;
}
command -v make >/dev/null
mkdir -p "$out"
# The board DTS includes a local base DTS. Build inside the prepared kernel
# source DTS directory so kernel dtc preprocessing resolves SoC includes.
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
cp "$source_root/board/mt6990-air-terminal-6.dts" "$tmp/"
cp "$dts" "$tmp/"
# Never modify the source tree or run a target-side operation. Use the kernel
# build's own dtc rules and headers in an isolated out-of-tree build.
echo "READY: input=$dts kernel=$kernel output=$out"
echo "MANUAL_GATE: integrate the candidate into the matching kernel DTS Makefile"
echo "and run make ARCH=arm64 dtbs; no DTB generated by this preflight."
